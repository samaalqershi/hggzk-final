#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

/**
 * Collects all Dart files recursively.
 * يجمع جميع ملفات Dart بشكل递归.
 */
function collectDartFiles(entry) {
  const stat = fs.statSync(entry);

  if (stat.isFile()) {
    return entry.endsWith('.dart') ? [entry] : [];
  }

  const results = [];

  for (const child of fs.readdirSync(entry)) {
    results.push(...collectDartFiles(path.join(entry, child)));
  }

  return results;
}

/**
 * Returns the declaration match when the current line represents a valid
 * top-level or class-member declaration for documentation.
 * يعيد التصريح المطابق عندما يمثل السطر تعريفًا صالحًا للتوثيق.
 */
function matchDeclaration(trimmed, currentType, state) {
  if (!trimmed || trimmed.startsWith('//')) {
    return null;
  }

  if (
    state.directiveContinuation ||
    state.expressionContinuation ||
    state.parenDepth > 0 ||
    state.bracketDepth > 0
  ) {
    return null;
  }

  const memberDepth = currentType ? currentType.bodyDepth : 0;
  const isTopLevel = !currentType && state.braceDepth === 0;
  const isMemberLevel = currentType && state.braceDepth === memberDepth;

  if (!isTopLevel && !isMemberLevel) {
    return null;
  }

  let match =
    trimmed.match(/^(abstract\s+class|class|enum|mixin)\s+([A-Za-z_][A-Za-z0-9_]*)\b/) ||
    trimmed.match(/^extension\s+([A-Za-z_][A-Za-z0-9_]*)?\s+on\b/) ||
    trimmed.match(/^typedef\s+([A-Za-z_][A-Za-z0-9_]*)\b/);

  if (match) {
    return true;
  }

  const ownerName = currentType?.name;

  if (
    ownerName &&
    trimmed.match(
      new RegExp(
        `^(?:const|factory)?\\s*(${ownerName}(?:\\.[A-Za-z_][A-Za-z0-9_]*)?)\\s*\\(`,
      ),
    )
  ) {
    return true;
  }

  if (
    trimmed.endsWith(';') &&
    !trimmed.includes('(') &&
    !/^(return|break|continue|assert|throw|import|export|part|library)\b/.test(
      trimmed,
    ) &&
    trimmed.match(
      /^(?:static\s+)?(?:(?:late\s+)?(?:final|const|var)\s+)?(?:[A-Za-z_][A-Za-z0-9_<>,? ]+\s+)([A-Za-z_][A-Za-z0-9_]*)\s*(?:=.*)?;$/,
    )
  ) {
    return true;
  }

  if (
    trimmed.match(
      /^(?:static\s+)?(?:[A-Za-z_][A-Za-z0-9_<>,? ]+\s+)?get\s+([A-Za-z_][A-Za-z0-9_]*)\b/,
    ) ||
    trimmed.match(
      /^(?:static\s+)?(?:[A-Za-z_][A-Za-z0-9_<>,? ]+\s+)?set\s+([A-Za-z_][A-Za-z0-9_]*)\b/,
    ) ||
    trimmed.match(
      /^(?:static\s+)?(?:FutureOr<[^>]+>|Future<[^>]+>|Future|Stream<[^>]+>|Widget|void|bool\??|int\??|double\??|String\??|Map<[^>]+>\??|List<[^>]+>\??|Set<[^>]+>\??|dynamic|[A-Za-z_][A-Za-z0-9_<>,? ]+)\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/,
    )
  ) {
    return true;
  }

  return null;
}

/**
 * Removes autogenerated bilingual docs that are placed before invalid targets.
 * يزيل التوثيق الثنائي المولد آليًا عندما يكون موضوعًا قبل هدف غير صالح.
 */
function cleanFile(filePath) {
  const input = fs.readFileSync(filePath, 'utf8');
  const lines = input.split('\n');
  const output = [];

  const state = {
    braceDepth: 0,
    parenDepth: 0,
    bracketDepth: 0,
    directiveContinuation: false,
    expressionContinuation: false,
  };

  let removed = 0;
  let pendingType = null;
  const typeStack = [];

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const trimmed = line.trim();
    const currentType = typeStack[typeStack.length - 1] || null;

    const isAutoDocPair =
      trimmed.startsWith('/// English:') &&
      index + 1 < lines.length &&
      lines[index + 1].trim().startsWith('/// العربية:');

    if (isAutoDocPair) {
      let probe = index + 2;

      while (
        probe < lines.length &&
        (lines[probe].trim() === '' || lines[probe].trim().startsWith('@'))
      ) {
        probe += 1;
      }

      const nextTrimmed = probe < lines.length ? lines[probe].trim() : '';
      const validTarget = matchDeclaration(nextTrimmed, currentType, state);

      if (!validTarget) {
        removed += 1;
        index += 1;
        continue;
      }
    }

    output.push(line);

    const opens = (line.match(/{/g) || []).length;
    const closes = (line.match(/}/g) || []).length;
    const parenOpens = (line.match(/\(/g) || []).length;
    const parenCloses = (line.match(/\)/g) || []).length;
    const bracketOpens = (line.match(/\[/g) || []).length;
    const bracketCloses = (line.match(/\]/g) || []).length;

    const typeMatch = trimmed.match(
      /^(?:abstract\s+class|class|enum|mixin)\s+([A-Za-z_][A-Za-z0-9_]*)\b/,
    );
    const extensionMatch = trimmed.match(
      /^extension\s+([A-Za-z_][A-Za-z0-9_]*)?\s+on\b/,
    );

    if (typeMatch && opens > 0) {
      typeStack.push({
        name: typeMatch[1],
        bodyDepth: state.braceDepth + opens,
      });
    } else if (typeMatch) {
      pendingType = typeMatch[1];
    } else if (extensionMatch && opens > 0) {
      typeStack.push({
        name: extensionMatch[1] || 'extension',
        bodyDepth: state.braceDepth + opens,
      });
    } else if (extensionMatch) {
      pendingType = extensionMatch[1] || 'extension';
    }

    if (/^(import|export|part)\b/.test(trimmed) && !trimmed.endsWith(';')) {
      state.directiveContinuation = true;
    } else if (state.directiveContinuation && trimmed.endsWith(';')) {
      state.directiveContinuation = false;
    }

    if (
      !state.expressionContinuation &&
      /=>\s*$/.test(trimmed) &&
      !trimmed.endsWith(';')
    ) {
      state.expressionContinuation = true;
    } else if (state.expressionContinuation && trimmed.includes(';')) {
      state.expressionContinuation = false;
    }

    state.braceDepth += opens;
    state.braceDepth -= closes;
    state.parenDepth += parenOpens;
    state.parenDepth -= parenCloses;
    state.bracketDepth += bracketOpens;
    state.bracketDepth -= bracketCloses;

    if (pendingType && opens > 0 && !typeMatch && !extensionMatch) {
      typeStack.push({
        name: pendingType,
        bodyDepth: state.braceDepth,
      });
      pendingType = null;
    }

    while (
      typeStack.length &&
      state.braceDepth < typeStack[typeStack.length - 1].bodyDepth
    ) {
      typeStack.pop();
    }
  }

  const next = output.join('\n');

  if (next !== input) {
    fs.writeFileSync(filePath, next);
  }

  return removed;
}

function main() {
  const rootArg = process.argv[2] || 'hggzk_app/lib';
  const root = path.resolve(process.cwd(), rootArg);

  if (!fs.existsSync(root)) {
    console.error(`Path not found: ${root}`);
    process.exit(1);
  }

  const files = collectDartFiles(root);
  let totalRemoved = 0;

  for (const file of files) {
    totalRemoved += cleanFile(file);
  }

  console.log(`Processed ${files.length} files.`);
  console.log(`Removed ${totalRemoved} invalid documentation blocks.`);
}

if (require.main === module) {
  main();
}
