import 'package:equatable/equatable.dart';

/// يمثل تقرير الحجوزات المجمّع للفترة المطلوبة مع تفاصيل اليوم والملخص
/// المالي والسلوكي الخاص بهذه النافذة الزمنية.
/// Represents an aggregated booking report for the requested period with
/// daily breakdowns and a financial/behavioral summary.
class BookingReport extends Equatable {
  /// العناصر اليومية التي تكوّن التقرير النهائي.
  /// The daily entries that make up the final report.
  final List<BookingReportItem> items;

  /// الملخص الأعلى مستوى الذي يقرأه المستخدم أو لوحة الإدارة بسرعة.
  /// The high-level summary that users or dashboards can read at a glance.
  final BookingReportSummary summary;

  /// بداية الفترة الزمنية التي يغطيها التقرير.
  /// The start of the time range covered by the report.
  final DateTime startDate;

  /// نهاية الفترة الزمنية التي يغطيها التقرير.
  /// The end of the time range covered by the report.
  final DateTime endDate;

  /// Creates a booking report snapshot for a specific date range.
  const BookingReport({
    required this.items,
    required this.summary,
    required this.startDate,
    required this.endDate,
  });
  @override

  /// تعتمد المساواة على النافذة الزمنية ومحتوى التقرير لأن أي تغيير فيها
  /// ينتج تقريرًا مختلفًا.
  /// Equality depends on the date window and the report content because any
  /// change there produces a different report.
  List<Object> get props => [items, summary, startDate, endDate];
}

/// يمثل صفًا يوميًا واحدًا داخل التقرير يبين العدد والإيراد والحركات
/// المرتبطة بهذا اليوم.
/// Represents one daily row inside the report, showing count, revenue, and
/// related booking movements for that day.
class BookingReportItem extends Equatable {
  /// اليوم الذي يلخصه هذا الصف.
  /// The day summarized by this row.
  final DateTime date;

  /// عدد الحجوزات المسجلة في هذا اليوم.
  /// The number of bookings recorded for the day.
  final int count;

  /// الإيراد الناتج عن الحجوزات في هذا اليوم.
  /// The revenue generated by bookings on this day.
  final double revenue;

  /// عدد عمليات تسجيل الوصول في هذا اليوم.
  /// The number of check-ins that happened on this day.
  final int checkIns;

  /// عدد عمليات تسجيل المغادرة في هذا اليوم.
  /// The number of check-outs that happened on this day.
  final int checkOuts;

  /// عدد الإلغاءات التي حدثت في هذا اليوم.
  /// The number of cancellations that happened on this day.
  final int cancellations;

  /// توزيع الحجوزات حسب الحالة داخل هذا اليوم.
  /// The booking distribution by status for this day.
  final Map<String, int> bookingsByStatus;

  /// Creates a daily report item for booking analytics.
  const BookingReportItem({
    required this.date,
    required this.count,
    required this.revenue,
    required this.checkIns,
    required this.checkOuts,
    required this.cancellations,
    required this.bookingsByStatus,
  });
  @override

  /// تعتمد المساواة على كل قيمة يومية لأن تغيير أي منها يغير معنى السطر.
  /// Equality depends on every daily value because changing any of them
  /// changes the meaning of the row.
  List<Object> get props => [
        date,
        count,
        revenue,
        checkIns,
        checkOuts,
        cancellations,
        bookingsByStatus,
      ];
}

/// يلخص التقرير بالأرقام الكبرى التي تهم التحليل السريع مثل الإيراد ومعدل
/// الإشغال ومصادر الحجز.
/// Summarizes the report with the headline numbers that matter for quick
/// analysis, such as revenue, occupancy, and booking sources.
class BookingReportSummary extends Equatable {
  /// إجمالي الحجوزات ضمن فترة التقرير.
  /// The total number of bookings within the report period.
  final int totalBookings;

  /// إجمالي الإيراد المحقق خلال الفترة.
  /// The total revenue earned during the period.
  final double totalRevenue;

  /// متوسط قيمة الحجز الواحد في هذه النافذة الزمنية.
  /// The average value of one booking in this time window.
  final double averageBookingValue;

  /// نسبة الإشغال الكلية المحسوبة من بيانات التقرير.
  /// The overall occupancy rate calculated from the report data.
  final double occupancyRate;

  /// إجمالي الليالي المحجوزة خلال الفترة.
  /// The total number of booked nights during the period.
  final int totalNights;

  /// متوسط طول الإقامة لكل حجز.
  /// The average stay length per booking.
  final double averageStayLength;

  /// توزيع الحجوزات بحسب مصدر الوصول أو القناة.
  /// The booking distribution by source or channel.
  final Map<String, int> bookingsBySource;

  /// توزيع الإيراد حسب وسيلة الدفع المستخدمة.
  /// The revenue distribution by payment method used.
  final Map<String, double> revenueByPaymentMethod;

  /// Creates the summary block for a booking report.
  const BookingReportSummary({
    required this.totalBookings,
    required this.totalRevenue,
    required this.averageBookingValue,
    required this.occupancyRate,
    required this.totalNights,
    required this.averageStayLength,
    required this.bookingsBySource,
    required this.revenueByPaymentMethod,
  });
  @override

  /// تعتمد المساواة على جميع مؤشرات الملخص لأنها تمثل صورة واحدة للتقرير.
  /// Equality depends on all summary indicators because they represent one
  /// snapshot of the report.
  List<Object> get props => [
        totalBookings,
        totalRevenue,
        averageBookingValue,
        occupancyRate,
        totalNights,
        averageStayLength,
        bookingsBySource,
        revenueByPaymentMethod,
      ];
}
