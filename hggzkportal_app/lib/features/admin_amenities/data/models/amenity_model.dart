import '../../domain/entities/amenity.dart';

/// يمثل نسخة البيانات الخاصة بالمرافق كما تصل من الخادم أو تعاد إليه،
/// مع أدوات تحويل مباشرة بين JSON وكيان الدومين.
/// Represents the amenity data shape as received from or sent to the backend,
/// with direct conversion helpers to and from the domain entity.
class AmenityModel extends Amenity {
  /// ينشئ نموذج المرفق مع كل خصائص العرض والحالة والإحصاءات المرتبطة به.
  /// Creates the amenity model with its display, state, and related statistics
  /// fields.
  const AmenityModel({
    required String id,
    required String name,
    required String description,
    required String icon,
    DateTime? createdAt,
    DateTime? updatedAt,
    bool? isActive,
    int? propertiesCount,
    double? averageExtraCost,
  }) : super(
          id: id,
          name: name,
          description: description,
          icon: icon,
          createdAt: createdAt,
          updatedAt: updatedAt,
          isActive: isActive,
          propertiesCount: propertiesCount,
          averageExtraCost: averageExtraCost,
        );

  /// يبني نموذج المرفق من بنية JSON القادمة من واجهة الإدارة أو API
  /// الموحد.
  /// Builds the amenity model from JSON returned by the admin API or a
  /// unified backend payload.
  factory AmenityModel.fromJson(Map<String, dynamic> json) {
    return AmenityModel(
      id: (json['id'] ?? json['amenityId'] ?? '').toString(),
      name: json['name'] ?? '',
      description: json['description'] ?? '',
      icon: (json['icon'] ?? json['iconUrl'] ?? 'star') as String,
      createdAt:
          json['createdAt'] != null ? DateTime.parse(json['createdAt']) : null,
      updatedAt:
          json['updatedAt'] != null ? DateTime.parse(json['updatedAt']) : null,
      isActive: json['isActive'] ?? json['active'] ?? true,
      propertiesCount: json['propertiesCount'] ?? 0,
      averageExtraCost: (json['averageExtraCost'] ?? 0).toDouble(),
    );
  }

  /// يحول نموذج المرفق إلى خريطة JSON جاهزة للإرسال أو التخزين.
  /// Converts the amenity model into a JSON map ready for transport or
  /// storage.
  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'name': name,
      'description': description,
      'icon': icon,
      if (createdAt != null) 'createdAt': createdAt!.toIso8601String(),
      if (updatedAt != null) 'updatedAt': updatedAt!.toIso8601String(),
      'isActive': isActive,
      'propertiesCount': propertiesCount,
      'averageExtraCost': averageExtraCost,
    };
  }

  /// يبني نموذجًا مطابقًا لكيان الدومين عندما نحتاج نسخة طبقة البيانات من
  /// كائن موجود بالفعل.
  /// Builds a model from an existing domain entity when the data layer needs a
  /// concrete transport representation.
  factory AmenityModel.fromEntity(Amenity entity) {
    return AmenityModel(
      id: entity.id,
      name: entity.name,
      description: entity.description,
      icon: entity.icon,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
      isActive: entity.isActive,
      propertiesCount: entity.propertiesCount,
      averageExtraCost: entity.averageExtraCost,
    );
  }
}

/// يمثل مؤشرات المرافق المجمعة التي تعتمد عليها بطاقات الإحصاءات في
/// لوحة الإدارة.
/// Represents aggregated amenity metrics used by admin dashboard statistic
/// cards.
class AmenityStatsModel {
  /// العدد الكلي للمرافق المسجلة في النظام.
  /// Total number of amenities registered in the system.
  final int totalAmenities;

  /// عدد المرافق التي لا تزال مفعلة ويمكن إسنادها أو عرضها.
  /// Number of amenities that remain active and can be assigned or displayed.
  final int activeAmenities;

  /// إجمالي مرات الإسناد أو الارتباط بين المرافق والعقارات.
  /// Total number of assignment or linkage records between amenities and
  /// properties.
  final int totalAssignments;

  /// مجموع الإيرادات الإضافية المرتبطة بتلك المرافق.
  /// Combined extra revenue generated by those amenities.
  final double totalRevenue;

  /// خريطة تعرض المرافق الأكثر شيوعًا وعدد ظهور كل منها.
  /// Map of the most popular amenities and how often each one appears.
  final Map<String, int> popularAmenities;

  /// خريطة تربط كل مرفق بالإيراد المنسوب إليه.
  /// Map that ties each amenity to its attributed revenue.
  final Map<String, double> revenueByAmenity;

  /// ينشئ مجموعة الإحصاءات المجمعة الخاصة بالمرافق مع كل الحقول اللازمة
  /// للعرض التحليلي.
  /// Creates the aggregated amenity statistics bundle with all fields needed
  /// for analytical display.
  AmenityStatsModel({
    required this.totalAmenities,
    required this.activeAmenities,
    required this.totalAssignments,
    required this.totalRevenue,
    required this.popularAmenities,
    required this.revenueByAmenity,
  });

  /// يبني نموذج الإحصاءات من JSON كما تعيده واجهة الخادم.
  /// Builds the statistics model from the JSON payload returned by the
  /// backend.
  factory AmenityStatsModel.fromJson(Map<String, dynamic> json) {
    return AmenityStatsModel(
      totalAmenities: json['totalAmenities'] ?? 0,
      activeAmenities: json['activeAmenities'] ?? 0,
      totalAssignments: json['totalAssignments'] ?? 0,
      totalRevenue: (json['totalRevenue'] ?? 0).toDouble(),
      popularAmenities: Map<String, int>.from(json['popularAmenities'] ?? {}),
      revenueByAmenity:
          Map<String, double>.from(json['revenueByAmenity'] ?? {}),
    );
  }
}
